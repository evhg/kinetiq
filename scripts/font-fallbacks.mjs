#!/usr/bin/env node
// Writes src/app/font-fallbacks.css: the metric-matched local fallbacks that Archivo and Saira paint with until the
// web fonts swap in (display: swap), so the swap moves nothing (CLS from the font swap ~0; DESIGN.md "Type").
//
// next/font's own fallback (adjustFontFallback) is one Arial face per family, sized for Archivo's default width and
// regular weight. Our headings are wdth 108 to 125 (font-variation-settings, which Arial ignores) and weight 560 to 600,
// so the fallback ran 8% (h1) to 30% (wordmark) narrower than Archivo and the hero re-wrapped at the swap. Here every
// width the site uses gets its own fallback family (`--font-display-<wdth>` in globals.css), and every weight range
// its own face, each with a size-adjust measured on the site's own words.
//
// Each family is listed twice: Arial-metric sources first (Arial on iOS, macOS and Windows; Liberation Sans or Arimo on
// Linux, same advance widths), then Roboto (Android), whose regular has Arial's average width (911 vs 913 / 2048) but
// whose bold is 6% narrower than Arial Bold (926 vs 983), so its bold faces get their own size-adjust.
//
// Usage:
//   node scripts/font-fallbacks.mjs                 write the CSS from the ratios below
//   node scripts/font-fallbacks.mjs --measure=URL   measure the ratios on a running build (with Liberation Sans
//                                                   installed, as in the sandbox) and print them; paste into RATIOS
//                                                   when the fonts, weights, widths or copy change a lot.

import { writeFileSync } from "node:fs";
import { join } from "node:path";

// Width of the web font over Arial (Liberation Sans) for the same text, size and weight, measured on /, /reserve,
// /reserve?tier=limited and the gate (2026-11-01). Archivo per wdth; weights: light 100-300 and regular 301-500 against
// Arial, semi 501-650 and bold 651-900 against Arial Bold. Widths measured only at semibold (108-125) take the wdth
// factor of their semibold for their other weights.
const ARCHIVO_100 = { light: 1.003, regular: 0.9815, semi: 0.9616, bold: 1.025 };
const ARCHIVO_SEMI = { 108: 1.0277, 110: 1.0744, 112: 1.085, 125: 1.2974 };
const SAIRA = { light: 1.0558, regular: 1.0366, medium: 1.049, bold: 0.979 };

const ARCHIVO = { ascent: 0.878, descent: 0.21 };
const SAIRA_METRICS = { ascent: 1.135, descent: 0.439 };
// Roboto Bold's average width against Arial Bold's (capsize metrics, latin).
const ROBOTO_BOLD = 983 / 926;

const SRC = {
  arial: ["Arial", "ArialMT", "Liberation Sans", "LiberationSans", "Arimo", "Arimo-Regular"],
  arialBold: ["Arial Bold", "Arial-BoldMT", "Liberation Sans Bold", "LiberationSans-Bold", "Arimo Bold", "Arimo-Bold"],
  roboto: ["Roboto", "Roboto-Regular"],
  robotoBold: ["Roboto Bold", "Roboto-Bold"],
};

const pct = (x) => `${(x * 100).toFixed(2)}%`;

function face(family, weights, src, size, m) {
  return [
    "@font-face {",
    `  font-family: "${family}";`,
    `  src: ${src.map((s) => `local("${s}")`).join(", ")};`,
    `  font-weight: ${weights};`,
    `  size-adjust: ${pct(size)};`,
    `  ascent-override: ${pct(m.ascent / size)};`,
    `  descent-override: ${pct(m.descent / size)};`,
    "  line-gap-override: 0%;",
    "}",
  ].join("\n");
}

// One family (Arial sources) and its Roboto twin, from four weight-range ratios.
function family(name, r, m, ranges) {
  const out = [];
  for (const [key, weights, bold] of ranges) {
    out.push(face(name, weights, bold ? SRC.arialBold : SRC.arial, r[key], m));
  }
  for (const [key, weights, bold] of ranges) {
    out.push(face(`${name} Roboto`, weights, bold ? SRC.robotoBold : SRC.roboto, bold ? r[key] * ROBOTO_BOLD : r[key], m));
  }
  return out;
}

const ARCHIVO_RANGES = [
  ["light", "100 300", false],
  ["regular", "301 500", false],
  ["semi", "501 650", true],
  ["bold", "651 900", true],
];
const SAIRA_RANGES = [
  ["light", "100 350", false],
  ["regular", "351 425", false],
  ["medium", "426 500", false],
  ["bold", "501 900", true],
];

function css() {
  const blocks = [
    "/* Generated by scripts/font-fallbacks.mjs: do not edit by hand. Metric-matched local fallbacks for Archivo (one",
    "   family per wdth the site uses) and Saira, so the swap to the web fonts moves no text. */",
  ];
  blocks.push(...family("KQ Archivo", ARCHIVO_100, ARCHIVO, ARCHIVO_RANGES));
  for (const [w, semi] of Object.entries(ARCHIVO_SEMI)) {
    const f = semi / ARCHIVO_100.semi;
    const r = Object.fromEntries(Object.entries(ARCHIVO_100).map(([k, v]) => [k, v * f]));
    blocks.push(...family(`KQ Archivo ${w}`, r, ARCHIVO, ARCHIVO_RANGES));
  }
  blocks.push(...family("KQ Saira", SAIRA, SAIRA_METRICS, SAIRA_RANGES));
  return blocks.join("\n") + "\n";
}

const measureArg = process.argv.find((a) => a.startsWith("--measure="));
if (measureArg) {
  await measure(measureArg.slice("--measure=".length));
} else {
  const file = join(process.cwd(), "src/app/font-fallbacks.css");
  writeFileSync(file, css());
  console.log("[font-fallbacks] wrote", file);
}

// Width ratio of the web font to Liberation Sans over every text run on the pages, per (family, wdth, weight).
async function measure(base) {
  const { chromium } = await import("@playwright/test");
  const { ndaCookie } = await import("./nda-cookie.mjs");
  const browser = await chromium.launch();
  const all = {};
  for (const [path, cookie] of [["/", true], ["/reserve", true], ["/reserve?tier=limited", true], ["/", false]]) {
    const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" });
    if (cookie) await ctx.addCookies([ndaCookie(base)]);
    const page = await ctx.newPage();
    await page.goto(new URL(path, base).toString(), { waitUntil: "networkidle" });
    await page.evaluate(() => document.fonts.ready);
    const res = await page.evaluate(async () => {
      const st = document.createElement("style");
      st.textContent =
        '@font-face{font-family:"M Fb";src:local("Liberation Sans");font-weight:100 500}' +
        '@font-face{font-family:"M Fb";src:local("Liberation Sans Bold");font-weight:501 900}';
      document.head.appendChild(st);
      const host = document.createElement("div");
      host.style.cssText = "position:absolute;left:0;top:0;visibility:hidden;white-space:nowrap";
      document.body.appendChild(host);
      const out = {};
      const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
      const runs = [];
      for (let n; (n = walker.nextNode()); ) {
        const t = n.textContent.replace(/\s+/g, " ").trim();
        if (t && n.parentElement && !n.parentElement.closest("script,style,svg")) runs.push([n.parentElement, t]);
      }
      for (const [el, t] of runs) {
        const cs = getComputedStyle(el);
        const first = cs.fontFamily.split(",")[0];
        const fam = /Saira/.test(first) ? "Saira" : /Archivo/.test(first) ? "Archivo" : null;
        if (!fam) continue;
        const w = /wdth"?\s+([\d.]+)/.exec(cs.fontVariationSettings)?.[1] ?? "100";
        const key = `${fam}|${fam === "Saira" ? "-" : w}|${cs.fontWeight}`;
        const span = (ff) => {
          const s = document.createElement("span");
          Object.assign(s.style, {
            fontFamily: ff,
            fontSize: "100px",
            fontWeight: cs.fontWeight,
            fontVariationSettings: cs.fontVariationSettings,
            fontVariantNumeric: cs.fontVariantNumeric,
            textTransform: cs.textTransform,
          });
          s.textContent = t;
          host.appendChild(s);
          return s;
        };
        await document.fonts.load(`${cs.fontWeight} 100px "M Fb"`);
        const a = span(`"${fam}"`);
        const b = span('"M Fb"');
        const o = (out[key] ??= { a: 0, b: 0, chars: 0 });
        o.a += a.getBoundingClientRect().width;
        o.b += b.getBoundingClientRect().width;
        o.chars += t.length;
        a.remove();
        b.remove();
      }
      return out;
    });
    for (const [k, v] of Object.entries(res)) {
      const o = (all[k] ??= { a: 0, b: 0, chars: 0 });
      o.a += v.a;
      o.b += v.b;
      o.chars += v.chars;
    }
    await ctx.close();
  }
  for (const k of Object.keys(all).sort()) console.log(k.padEnd(20), (all[k].a / all[k].b).toFixed(4), `${all[k].chars} chars`);
  await browser.close();
}
